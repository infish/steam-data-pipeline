"""Generate docs/data_dictionary.md from information_schema.

    PYTHONPATH=src python scripts/generate_data_dictionary.py          # write
    PYTHONPATH=src python scripts/generate_data_dictionary.py --check  # verify

Structure (tables, views, columns, types, keys) comes from a migrated
database (the usual MYSQL_* settings); descriptions come from
docs/data_dictionary.json. Every table and view must have a description, so a
new migration cannot leave the dictionary incomplete. --check exits 1 when
the committed file differs from what the database would produce; CI runs it
after migrating a fresh database.
"""

import argparse
import json
import sys
from pathlib import Path

from database.mysql_database import get_connection


ROOT = Path(__file__).resolve().parents[1]
DESCRIPTIONS = ROOT / "docs" / "data_dictionary.json"
OUTPUT = ROOT / "docs" / "data_dictionary.md"


def read_schema(connection):
    cursor = connection.cursor()
    cursor.execute(
        """
        SELECT TABLE_NAME, TABLE_TYPE
        FROM information_schema.TABLES
        WHERE TABLE_SCHEMA = DATABASE()
        ORDER BY TABLE_NAME
        """
    )
    objects = {name: kind for name, kind in cursor.fetchall()}
    cursor.execute(
        """
        SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_KEY,
               EXTRA
        FROM information_schema.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE()
        ORDER BY TABLE_NAME, ORDINAL_POSITION
        """
    )
    columns = {}

    for table, column, column_type, nullable, key, extra in cursor.fetchall():
        columns.setdefault(table, []).append({
            "name": column,
            "type": column_type,
            "nullable": nullable == "YES",
            "key": key,
            "generated": "GENERATED" in (extra or "").upper(),
        })

    cursor.close()
    return objects, columns


def problems_with(objects, descriptions):
    described = {
        name
        for layer in descriptions["layers"]
        for name in layer["objects"]
    }
    missing = sorted(set(objects) - described)
    stale = sorted(described - set(objects))
    problems = []

    if missing:
        problems.append(
            "No description in docs/data_dictionary.json for: "
            + ", ".join(missing)
        )

    if stale:
        problems.append(
            "Described but not in the database: " + ", ".join(stale)
        )

    return problems


def key_label(column):
    labels = {"PRI": "PK", "UNI": "unique", "MUL": "index"}
    label = labels.get(column["key"], "")

    if column["generated"]:
        label = (label + ", generated").strip(", ")

    return label


def render(objects, columns, descriptions):
    lines = [
        "# Data dictionary",
        "",
        "<!-- Generated by scripts/generate_data_dictionary.py from",
        "     information_schema and docs/data_dictionary.json. Edit the",
        "     JSON, not this file. -->",
        "",
        descriptions["introduction"],
        "",
    ]

    for layer in descriptions["layers"]:
        lines += [f"## {layer['title']}", "", layer["description"], ""]

        for name, entry in layer["objects"].items():
            kind = "view" if objects[name] == "VIEW" else "table"
            lines += [f"### `{name}` ({kind})", "", entry["description"], ""]
            lines += [
                "| Column | Type | Null | Key | Description |",
                "| --- | --- | --- | --- | --- |",
            ]
            notes = entry.get("columns", {})

            for column in columns[name]:
                lines.append(
                    f"| `{column['name']}` | {column['type']} |"
                    f" {'yes' if column['nullable'] else 'no'} |"
                    f" {key_label(column)} |"
                    f" {notes.get(column['name'], '')} |"
                )

            unknown = sorted(set(notes) - {c["name"] for c in columns[name]})

            if unknown:
                raise ValueError(
                    f"{name}: described columns not in the database: "
                    + ", ".join(unknown)
                )

            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    descriptions = json.loads(DESCRIPTIONS.read_text())
    connection = get_connection()

    try:
        objects, columns = read_schema(connection)
    finally:
        connection.close()

    problems = problems_with(objects, descriptions)

    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1

    text = render(objects, columns, descriptions)

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(
                "docs/data_dictionary.md is out of date; run"
                " scripts/generate_data_dictionary.py and commit the result.",
                file=sys.stderr
            )
            return 1

        print("docs/data_dictionary.md is up to date.")
        return 0

    OUTPUT.write_text(text)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
